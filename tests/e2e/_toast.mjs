import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';
const root = '/home/claude/trail-site';
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css' };
const srv = createServer((req, res) => { let p = join(root, decodeURIComponent(req.url.split('?')[0])); if (existsSync(p) && statSync(p).isDirectory()) p = join(p, 'index.html'); if (!existsSync(p)) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'content-type': mime[extname(p)] || 'application/octet-stream' }); res.end(readFileSync(p)); }).listen(4482);
const b = await chromium.launch({ channel: 'chromium' });
const page = await b.newPage({ viewport: { width: 1280, height: 860 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:4482/b3/');
await page.locator('.compo').scrollIntoViewIfNeeded(); await page.waitForTimeout(1500);
const panel = await (await page.$('#cpanel')).contentFrame();
const form = await (await page.$('#cform')).contentFrame();
const out = {};
await panel.click('.icon-btn[aria-label]:not(.theme)'.replace(':not(.theme)', ':last-child'));
out.toastShown = await panel.evaluate(() => document.querySelector('.toast')?.textContent);
await form.evaluate(() => document.querySelector('label[for="incident.impact"] .trail-host').shadowRoot.querySelector('button').click());
await page.waitForTimeout(1500);
out.toastAfterFieldChange = await panel.evaluate(() => !!document.querySelector('.toast'));
await panel.click('.icon-btn[aria-label]:last-child'); await page.waitForTimeout(3600);
out.toastAfter3600 = await panel.evaluate(() => !!document.querySelector('.toast'));
// cursor
await page.mouse.move(100, 100); await page.waitForTimeout(200);
out.cursorVisibleOutside = !(await page.evaluate(() => document.getElementById('cursor').classList.contains('hid')));
const box = await page.locator('#cform').boundingBox();
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 8 }); await page.waitForTimeout(200);
out.cursorHiddenInIframe = await page.evaluate(() => document.getElementById('cursor').classList.contains('hid'));
console.log(JSON.stringify({ out, errs }));
await b.close(); srv.close();
