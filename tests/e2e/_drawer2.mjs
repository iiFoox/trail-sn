import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '../../extension/dist');
const outDir = process.argv[2];
const ctx = await chromium.launchPersistentContext(mkdtempSync(resolve(tmpdir(), 'trail-wi-')), { headless: true, channel: 'chromium', colorScheme: process.argv[3] || 'dark', deviceScaleFactor: 1, args: [`--disable-extensions-except=${dist}`, `--load-extension=${dist}`] });
let [sw] = ctx.serviceWorkers(); if (!sw) sw = await ctx.waitForEvent('serviceworker', { timeout: 15000 });
const id = new URL(sw.url()).host;
const page = await ctx.newPage(); const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.setViewportSize({ width: 400, height: 1000 });
await page.goto(`chrome-extension://${id}/src/sidepanel/index.html?demo=1`);
await page.waitForSelector('details.drawer summary'); await page.click('details.drawer summary'); await page.waitForTimeout(300); await page.click('.manual-mode button:nth-child(2)'); await page.waitForTimeout(300);
await page.waitForTimeout(900);
await page.screenshot({ path: resolve(outDir, `drawer-${process.argv[3] || 'dark'}.png`), fullPage: false });
console.log(JSON.stringify({ errors, boxes: await page.$$eval('.tabpane .box', (b) => b.length) }));
await ctx.close();
