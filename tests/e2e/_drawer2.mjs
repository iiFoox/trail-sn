import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '../../extension/dist');
const outDir = process.argv[2];
const ctx = await chromium.launchPersistentContext(mkdtempSync(resolve(tmpdir(), 'trail-wi-')), { headless: true, channel: 'chromium', colorScheme: process.argv[3] || 'dark', deviceScaleFactor: 1, args: [`--disable-extensions-except=${dist}`, `--load-extension=${dist}`] });
let [sw] = ctx.serviceWorkers(); if (!sw) sw = await ctx.waitForEvent('serviceworker', { timeout: 15000 });
const id = new URL(sw.url()).host;
const page = await ctx.newPage(); const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.setViewportSize({ width: 400, height: 1000 });
await page.goto(`chrome-extension://${id}/src/sidepanel/index.html?demo=1&tab=history&hist=record`);
await page.waitForSelector('.cmpbar button');
await page.click('.cmpbar button');
await page.waitForTimeout(200);
if (outDir) await page.screenshot({ path: resolve(outDir, `cmp-pick-${process.argv[3] || 'dark'}.png`), fullPage: false });
await page.click('ol.rtl > li:nth-child(1) .hd');
await page.click('ol.rtl > li:nth-child(4) .hd');
await page.waitForSelector('.card.cmp');
if (outDir) await page.screenshot({ path: resolve(outDir, `cmp-diff-${process.argv[3] || 'dark'}.png`), fullPage: false });
await page.waitForSelector('details.drawer summary'); await page.click('details.drawer summary'); await page.waitForTimeout(200); await page.click('.manual-mode button:nth-child(2)'); await page.waitForTimeout(200);
if (outDir) await page.screenshot({ path: resolve(outDir, `drawer-${process.argv[3] || 'dark'}.png`), fullPage: false });
await page.click('details.drawer .btn.primary');
await page.waitForSelector('.batch .bt-head.run');
if (outDir) await page.screenshot({ path: resolve(outDir, `drawer-rec-run-${process.argv[3] || 'dark'}.png`), fullPage: false });
await page.waitForSelector('.batch .bt-head.ok', { timeout: 3000 });
await page.waitForTimeout(400);
if (outDir) await page.screenshot({ path: resolve(outDir, `drawer-rec-done-${process.argv[3] || 'dark'}.png`), fullPage: false });
console.log(JSON.stringify({ errors, rows: await page.$$eval('.batch .bt-row', (b) => b.length) }));
await ctx.close();
