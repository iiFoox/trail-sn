import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
const root = '/home/claude/trail-site', S = '/tmp/claude-0/-home-claude/1355b350-d507-52b2-99e3-d63903bae67d/scratchpad/';
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css' };
const srv = createServer((req, res) => { const p = join(root, req.url.split('?')[0]); if (!existsSync(p)) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'content-type': mime[extname(p)] }); res.end(readFileSync(p)); }).listen(4486);
const b = await chromium.launch({ channel: 'chromium' });
const page = await b.newPage({ viewport: { width: 433, height: 1000 }, deviceScaleFactor: 1.5 });
const errs=[]; page.on('pageerror', (e) => errs.push(e.message));
await page.goto(`http://localhost:4486/demo/panel.html?theme=dark&lang=pt&field=impact`); await page.waitForTimeout(1500);
await page.screenshot({ path: `${S}f-answer.png` });
const plain = await page.$eval('.plain p', (e) => e.textContent).catch(() => 'SEM .plain');
await page.goto(`http://localhost:4486/demo/panel.html?theme=dark&lang=pt&field=impact&tab=proof`); await page.waitForTimeout(1500);
const cf = await page.$('.box.conflict'); if (cf) await cf.scrollIntoViewIfNeeded();
await page.screenshot({ path: `${S}f-conflict.png` });
await page.goto(`http://localhost:4486/demo/panel.html?theme=light&lang=pt&field=state&tab=history&hist=record`); await page.waitForTimeout(1500);
await page.click('.cmpbar .btn');
const pks = await page.$$('ol.rtl .pk'); await pks[0]?.click(); await pks[2]?.click(); await page.waitForTimeout(500);
await page.screenshot({ path: `${S}f-compare.png` });
const cmp = await page.$eval('.card.cmp', (e) => e.innerText).catch(() => 'SEM .cmp');
console.log(JSON.stringify({ errs, plain, pks: pks.length, cmp })); await b.close(); srv.close();
