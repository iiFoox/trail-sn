import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
const S = '/tmp/claude-0/-home-claude/1355b350-d507-52b2-99e3-d63903bae67d/scratchpad/';
const dist = resolve(dirname(fileURLToPath(import.meta.url)), '../../extension/dist');
const ctx = await chromium.launchPersistentContext(mkdtempSync(resolve(tmpdir(), 'trail-')), { headless: true, channel: 'chromium', args: [`--disable-extensions-except=${dist}`, `--load-extension=${dist}`], viewport: { width: 420, height: 700 }, deviceScaleFactor: 2 });
let [sw] = ctx.serviceWorkers(); if (!sw) sw = await ctx.waitForEvent('serviceworker');
const id = new URL(sw.url()).host;
const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`chrome-extension://${id}/src/sidepanel/index.html`); await p.waitForTimeout(800);
await p.screenshot({ path: S + 'drawer1.png' });
await p.click('.drawer-x'); await p.waitForTimeout(300);
const open1 = await p.evaluate(() => document.querySelector('.drawer').open);
await p.screenshot({ path: S + 'drawer2.png' });
await p.click('.drawer summary'); await p.waitForTimeout(300);
const open2 = await p.evaluate(() => document.querySelector('.drawer').open);
console.log(JSON.stringify({ errs, afterX: open1, afterReopen: open2 })); await ctx.close();
