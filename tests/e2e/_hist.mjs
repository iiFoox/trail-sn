import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
const root = '/home/claude/trail-site', S = '/tmp/claude-0/-home-claude/1355b350-d507-52b2-99e3-d63903bae67d/scratchpad/';
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css' };
const srv = createServer((req, res) => { const p = join(root, req.url.split('?')[0]); if (!existsSync(p)) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'content-type': mime[extname(p)] }); res.end(readFileSync(p)); }).listen(4485);
const b = await chromium.launch({ channel: 'chromium' });
const page = await b.newPage({ viewport: { width: 433, height: 900 }, deviceScaleFactor: 2 });
const errs=[]; page.on('pageerror', (e) => errs.push(e.message));
await page.goto(`http://localhost:4485/demo/panel.html?theme=dark&lang=pt&field=state&tab=history&hist=record`); await page.waitForTimeout(900);
await page.evaluate(() => { document.querySelectorAll('details.fold').forEach((d) => d.open = true); const g = document.querySelectorAll('details.grp'); if (g[0]) g[0].open = true; if (g[1]) g[1].open = true; });
await page.waitForTimeout(200);
await page.waitForTimeout(800); await page.screenshot({ path: `${S}tl.png`, fullPage: true });
console.log(JSON.stringify(errs)); await b.close(); srv.close();
